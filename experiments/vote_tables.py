"""Item 14a: the report's tables, generated from the results files so no number is typed.

    uv run experiments/vote_tables.py --dir docs/reports/2026-10-31-vote-orderings --summary docs/reports/2026-10-30-deep-pass/summary.json

Writes <dir>/tables.md from orderings.json, lowered.json and item 14's summary.json.
"""

import argparse
import json
from pathlib import Path

LISTS = [("frozen_v1", "frozen-v1"), ("combined", "combined"), ("combined_votes", "combined + vote rule"), ("a", "(a)"), ("a_votes", "(a) + vote rule"), ("b", "(b)")]
SENSITIVITY = [("b_factor_2", "(b), factor 2"), ("b_factor_8", "(b), factor 8")]
RATE_DEPTH = [("a_rate_depth", "(a), votes to the N100 rate only"), ("b_rate_depth", "(b), votes to the N100 rate only")]


def pct(iv: list[float]) -> str:
    return f"{iv[0] * 100:.0f}-{iv[1] * 100:.0f}"


def key_rows(o: dict, lists: list) -> list[str]:
    out = ["| list | 10 | 20 | 50 | 100 | 250 |", "|---|---|---|---|---|---|"]
    for name, label in lists:
        k = o["key"][name]
        out.append(f"| {label} | " + " | ".join(f"{k['curve'][n]} ({pct(k['interval_95'][n])})" for n in ("10", "20", "50", "100", "250")) + " |")
    return out


def tp_rows(o: dict, lists: list) -> list[str]:
    out = ["| list | N10 | N20 | N50 | N100 | N250 | board rate |", "|---|---|---|---|---|---|---|"]
    for name, label in lists:
        t = o["transplant"][name]
        out.append(f"| {label} | " + " | ".join(f"{t[n]['found']} ({pct(t[n]['interval_95'])})" for n in ("N10", "N20", "N50", "N100", "N250", "board_rate")) + " |")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dir", required=True)
    ap.add_argument("--summary", required=True)
    a = ap.parse_args()
    d = Path(a.dir)
    o, low, s = json.loads((d / "orderings.json").read_text()), json.loads((d / "lowered.json").read_text()), json.loads(Path(a.summary).read_text())
    w = ["# Tables for item 14a, generated by experiments/vote_tables.py", "", f"## Key, found of {o['key']['combined']['n']}, 95 percent Wilson interval in percent", ""]
    w += key_rows(o, LISTS) + ["", "Sensitivity only:", ""] + key_rows(o, SENSITIVITY)
    w += ["", f"## Transplant, found of {o['transplant']['combined']['N20']['n']}, 95 percent Wilson interval in percent", "", "False alarms allowed over the board's pool: " + ", ".join(f"{k} {v}" for k, v in o["transplant_allowed_false_alarms"].items()), ""]
    w += tp_rows(o, LISTS) + ["", "Sensitivity only:", ""] + tp_rows(o, SENSITIVITY) + ["", "Added after seeing the board:", ""] + tp_rows(o, RATE_DEPTH)

    w += ["", "## Moves across the top 20, against the combined list", ""]
    for name, label in LISTS + SENSITIVITY + RATE_DEPTH:
        if name in ("combined",):
            continue
        if name in o["moved_key"]:
            m = o["moved_key"][name]
            w.append(f"- **{label}, key.** Out: " + (", ".join(f"{x['piece']} ({x['combined']} to {x['here']})" for x in m["out"]) or "none") + ". In: " + (", ".join(f"{x['piece']} ({x['combined']} to {x['here']})" for x in m["in"]) or "none") + ".")
        m = o["moved_transplant"][name]
        fmt = lambda x: f"{x['site']}/{x['piece']} {x['size_m']} m on {x['target']}"  # noqa: E731
        w.append(f"- **{label}, transplant at N20.** Out ({len(m['out'])}): " + (", ".join(fmt(x) for x in m["out"]) or "none") + f". In ({len(m['in'])}): " + (", ".join(fmt(x) for x in m["in"]) or "none") + ".")

    w += ["", "## Lowered detections on a planted piece", "", "Sheet number is the number on lowered_planted.png.", "",
          "| sheet | planted piece | size, m | truth | branch | area, px | px from the piece's centre (radius) | depth in its own fold | found on combined at | found with the vote rule at | votes |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for i, x in enumerate(low["lowered"]):
        for p in x["on_planted"]:
            votes = ", ".join(f"{v['verdict']} {v['confidence']}" for v in x["votes"])
            w.append(f"| {i + 1} | {p['site']}/{p['piece']} | {p['size_m']} | {p['truth']} | {x['branch']} | {x['area_px']} | {p['distance_px']} ({p['radius_px']}) | {x['depth_in_own_fold']} | {', '.join(p['found_combined']) or 'none'} | {', '.join(p['found_with_vote_rule']) or 'none'} | {votes} |")

    w += ["", "## Lowered detections on no planted piece", "", "| sheet | branch | area, px | best depth in any fold | valid fraction | votes |", "|---|---|---|---|---|---|"]
    for i, x in enumerate(low["lowered"]):
        if not x["on_planted"]:
            w.append(f"| {i + 1} | {x['branch']} | {x['area_px']} | {x['best_depth_any_fold']} | {x['valid_fraction']} | " + ", ".join(f"{v['verdict']} {v['confidence']}" for v in x["votes"]) + " |")

    w += ["", "## Spark's lowered rows on recorded pieces", "", "| strip | piece | combined rank | branch | first vote | cites | Spark's reason |", "|---|---|---|---|---|---|---|"]
    for r in low["review_lowered_recorded_rows"]:
        w.append(f"| {r['strip']} | {', '.join(r['pieces'])} | {r['rank']} | {r['branch']} | {r['first_vote']['verdict']} {r['first_vote']['confidence']} | {', '.join(r['verdict']['cites'])} | {r['verdict']['reason']} |")

    w += ["", "## Item 14, per strip (summary.json)", "", "| strip | site | voted | votes | band | lowered by votes | share | flagged over 0.9 | review verdicts | further lowered by review |", "|---|---|---|---|---|---|---|---|---|---|"]
    for sid, p in s["per_strip"].items():
        w.append(f"| {sid} | {p['site']} | {p['voted']} | {p['votes']} | {p['band']} | {p['lowered_by_votes']} | {p['share_lowered']} | {'yes' if p['flag_over_share'] else 'no'} | {p['review_verdicts']} | {p['lowered_by_review']} |")

    w += ["", "## Item 14, false alarms cleared above each recorded piece (summary.json; votes and review together)", "", "| strip | piece | rank on combined | false alarms above | voted above | cleared above |", "|---|---|---|---|---|---|"]
    not_listed = []
    for sid, p in s["per_strip"].items():
        for q in p["pieces"]:
            if q["listed"]:
                w.append(f"| {sid} | {p['site']}/{q['piece']} | {q['rank_before']} | {q['false_alarms_above']} | {q['voted_above']} | {q['cleared_above']} |")
            else:
                not_listed.append(f"{p['site']}/{q['piece']}/{sid}")
    w += ["", "Not on the combined list, so no vote can reach them: " + ", ".join(not_listed) + "."]

    w += ["", "## First votes by strip (orderings.json)", "", "| strip | hardware | natural | unsure | lowered |", "|---|---|---|---|---|"]
    for sid, c in o["vote_counts"]["key"].items():
        w.append(f"| {sid} | {c['first_hardware']} | {c['first_natural']} | {c['first_unsure']} | {c['lowered']} |")

    w += ["", "## First votes by what the row is (lowered.json)", "", "| board | row | hardware | natural | unsure |", "|---|---|---|---|---|"]
    for board, field in (("key lists", "first_votes_key_lists"), ("transplant", "first_votes_transplant")):
        groups = sorted({k.split("/")[0] for k in low[field]})
        for g in groups:
            w.append(f"| {board} | {g} | {low[field].get(g + '/hardware', 0)} | {low[field].get(g + '/natural', 0)} | {low[field].get(g + '/unsure', 0)} |")

    w += ["", "## Counts (lowered.json)", "", "```", json.dumps({k: low[k] for k in ("transplant_voted", "transplant_lowered", "lowered_on_planted", "lowered_on_sham", "planted_pieces", "distinct_planted_pieces_under_a_lowered_detection", "planted_pieces_with_a_voted_detection", "shams", "price_check", "review_totals")}, indent=1), "```", ""]
    (d / "tables.md").write_text("\n".join(w))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
